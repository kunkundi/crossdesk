class ScopedD3dMultithreadLock {
 public:
  explicit ScopedD3dMultithreadLock(ID3D11DeviceContext* context) noexcept {
    if (context &&
        SUCCEEDED(
            context->QueryInterface(IID_PPV_ARGS(lock_.GetAddressOf()))) &&
        lock_ && lock_->GetMultithreadProtected()) {
      lock_->Enter();
      locked_ = true;
    }
  }
  ~ScopedD3dMultithreadLock() {
    if (locked_ && lock_) {
      lock_->Leave();
    }
  }
  ScopedD3dMultithreadLock(const ScopedD3dMultithreadLock&) = delete;
  ScopedD3dMultithreadLock& operator=(const ScopedD3dMultithreadLock&) = delete;

 private:
  Microsoft::WRL::ComPtr<ID3D10Multithread> lock_;
  bool locked_ = false;
};

bool ConstantsEqual(const HdrShaderConstants& a,
                    const HdrShaderConstants& b) noexcept {
  return a.mode == b.mode &&
         a.inv_sdr_white_scale == b.inv_sdr_white_scale &&
         a.max_headroom == b.max_headroom && a.shoulder_c == b.shoulder_c;
}

